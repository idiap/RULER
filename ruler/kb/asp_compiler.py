"""Deterministic compiler from typed RULER logical IR to clingo ASP."""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from datetime import date

import clingo

from ruler.kb.formalization import PredicateRegistry
from ruler.kb.logical_ir import (
    Aggregation,
    ArithmeticTerm,
    Atom,
    Comparison,
    Constant,
    ExpressionKind,
    IRStatement,
    LogicalExpression,
    LogicalProgram,
    Modality,
    Scalar,
    Term,
    Variable,
)

COMPILER_VERSION = "ruler-ir-asp/1"


@dataclass(frozen=True)
class CompiledASP:
    """Stable compiler output and its content identity."""

    program_id: str
    compiler_version: str
    text: str
    sha256: str


class ASPCompilationError(ValueError):
    """Raised when valid IR uses a construct without approved ASP lowering."""


def compile_asp(
    program: LogicalProgram,
    registry: PredicateRegistry | None = None,
) -> CompiledASP:
    """Compile facts, rules, constraints, aggregates, and show directives."""
    vocabulary = registry or PredicateRegistry()
    lines = [f"% generated by {COMPILER_VERSION}", f"% program: {program.program_id}"]
    for statement in sorted(program.statements, key=lambda item: item.statement_id):
        lines.extend(_compile_statement(statement, vocabulary))
    for directive in sorted(program.show, key=lambda item: (item.predicate, item.arity)):
        signature = vocabulary.require(directive.predicate)
        if signature.arity != directive.arity:
            raise ASPCompilationError(
                f"show arity mismatch for {directive.predicate}: "
                f"expected {signature.arity}, got {directive.arity}"
            )
        lines.append(f"#show {directive.predicate}/{directive.arity}.")
    text = "\n".join(lines) + "\n"
    try:
        control = clingo.Control(["--warn=none"])
        control.add("base", [], text)
        control.ground([("base", [])])
    except RuntimeError as exc:
        raise ASPCompilationError(f"generated ASP failed clingo validation: {exc}") from exc
    digest = "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()
    return CompiledASP(program.program_id, COMPILER_VERSION, text, digest)


def render_asp_atom(atom: Atom, registry: PredicateRegistry | None = None) -> str:
    """Render one ground or variable atom using the compiler's checked vocabulary."""
    return _render_atom(atom, registry or PredicateRegistry())


def _compile_statement(
    statement: IRStatement,
    registry: PredicateRegistry,
) -> list[str]:
    lines = [f"% statement: {statement.statement_id}"]
    head = _render_atom(statement.head, registry) if statement.head else None
    if statement.modality == Modality.FACT:
        lines.append(f"{head}.")
        return lines
    if statement.body is None:
        raise ASPCompilationError(f"statement {statement.statement_id} has no body")
    body = _render_expression(statement.body, registry)
    lines.append(f"{head} :- {body}." if head else f":- {body}.")
    return lines


def _render_expression(expression: LogicalExpression, registry: PredicateRegistry) -> str:
    if expression.kind == ExpressionKind.ATOM:
        return _render_atom(_required(expression.atom, "atom"), registry)
    if expression.kind == ExpressionKind.NEGATION:
        operand = expression.operands[0]
        if operand.kind != ExpressionKind.ATOM:
            raise ASPCompilationError("default negation currently requires an atom operand")
        return "not " + _render_atom(_required(operand.atom, "negated atom"), registry)
    if expression.kind == ExpressionKind.CONJUNCTION:
        return ", ".join(_render_expression(item, registry) for item in expression.operands)
    if expression.kind == ExpressionKind.DISJUNCTION:
        choices = "; ".join(_render_expression(item, registry) for item in expression.operands)
        return f"1 {{ {choices} }}"
    if expression.kind == ExpressionKind.COMPARISON:
        return _render_comparison(_required(expression.comparison, "comparison"))
    if expression.kind == ExpressionKind.AGGREGATION:
        return _render_aggregation(_required(expression.aggregation, "aggregation"), registry)
    if expression.kind == ExpressionKind.EXCEPTION:
        target = _render_atom(_required(expression.exception_target, "exception target"), registry)
        body = _render_expression(expression.operands[0], registry)
        return f"{body}, not {target}"
    if expression.kind in {ExpressionKind.TEMPORAL, ExpressionKind.PRIORITY}:
        raise ASPCompilationError(
            f"{expression.kind.value} must be normalized to declared predicates before ASP compilation"
        )
    raise ASPCompilationError(f"unsupported expression: {expression.kind.value}")


def _render_atom(atom: Atom, registry: PredicateRegistry) -> str:
    signature = registry.require(atom.predicate)
    if len(atom.arguments) != signature.arity:
        raise ASPCompilationError(
            f"arity mismatch for {atom.predicate}: expected {signature.arity}, got {len(atom.arguments)}"
        )
    for index, (argument, expected) in enumerate(
        zip(atom.arguments, signature.argument_types, strict=True)
    ):
        if argument.value_type != expected:
            raise ASPCompilationError(
                f"type mismatch for {atom.predicate}/{signature.arity} argument {index + 1}: "
                f"expected {expected.value}, got {argument.value_type.value}"
            )
        domain = signature.value_domains[index] if signature.value_domains else None
        if domain and isinstance(argument, Constant) and str(argument.value) not in domain:
            raise ASPCompilationError(
                f"value-domain mismatch for {atom.predicate}/{signature.arity} argument "
                f"{index + 1}: {argument.value!r} is not in {domain}"
            )
    prefix = "-" if atom.classical_negation else ""
    arguments = ",".join(_render_term(argument) for argument in atom.arguments)
    return f"{prefix}{atom.predicate}({arguments})"


def _render_comparison(comparison: Comparison) -> str:
    return f"{_render_scalar(comparison.left)} {comparison.operator} {_render_scalar(comparison.right)}"


def _render_aggregation(aggregation: Aggregation, registry: PredicateRegistry) -> str:
    operator = f"#{aggregation.operator}"
    variable = _render_term(aggregation.variable)
    atom = _render_atom(aggregation.atom, registry)
    bound = _render_term(aggregation.bound)
    return f"{operator} {{ {variable} : {atom} }} {aggregation.comparison} {bound}"


def _render_scalar(value: Scalar) -> str:
    if isinstance(value, ArithmeticTerm):
        return f"({_render_term(value.left)} {value.operator} {_render_term(value.right)})"
    return _render_term(value)


def _render_term(term: Term) -> str:
    if isinstance(term, Variable):
        return term.name
    value = term.value
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, date):
        value = value.isoformat()
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _required[T](value: T | None, label: str) -> T:
    if value is None:
        raise ASPCompilationError(f"missing {label}")
    return value
