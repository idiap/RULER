"""Alembic environment; credentials come exclusively from the environment."""

from alembic import context
from ruler.persistence.database import database_engine, database_url
from ruler.persistence.schema import metadata

if context.is_offline_mode():
    context.configure(url=database_url(), target_metadata=metadata, literal_binds=True)
    with context.begin_transaction():
        context.run_migrations()
else:
    engine = database_engine()
    try:
        with engine.connect() as connection:
            context.configure(connection=connection, target_metadata=metadata)
            with context.begin_transaction():
                context.run_migrations()
    finally:
        engine.dispose()
